// Assets are the official player and the terminal font. BoxFont, when set,
// is served as ExportBox with unicode-range U+2500-257F ahead of ExportMono:
// box drawing whose vertical strokes span the player's line box (the
// library's AgentReelBox.ttf, generated by scripts/box-font.py).
type Assets struct{ PlayerJS, PlayerCSS, Font, BoxFont []byte }
type Config struct {
	Chromium, FFmpeg, FFprobe string
	Assets                    Assets
	// NoSandbox is only for an already isolated synthetic build sandbox.
	NoSandbox bool
}

// Span selects [Start, End) on the supplied cast's playback clock. Gaps between
// spans are omitted in video; source positions and optional wall-clock provenance
// remain in the result. The caller supplies correct, archive-derived provenance.
type Span struct {
	Start     float64    `json:"sourceStartSeconds"`
	End       float64    `json:"sourceEndSeconds"`
	Segment   int        `json:"segment,omitempty"`
	WallStart *time.Time `json:"wallStart,omitempty"`
	WallEnd   *time.Time `json:"wallEnd,omitempty"`
}
type Request struct {
	// Cast is a caller-verified immutable local input positioned at its header.
	// The caller owns/ closes it; arbitrary blocking network readers are unsupported.
	Cast io.Reader
	// Output is an explicit trusted local destination, not an HTTP path. It must
	// not already exist. Output's parent must be caller-owned and trusted.
	Output             string
	Spans              []Span
	FPS, Width, Height int
	Codec              string // h264 (.mp4) or prores (.mov)
}
type Timing struct {
	Span
	FirstFrame int `json:"firstFrame"`
	Frames     int `json:"frames"`
}
type Result struct {
	Codec           string   `json:"codec"`
	FPS             int      `json:"fps"`
	Width           int      `json:"width"`
	Height          int      `json:"height"`
	Frames          int      `json:"frames"`
	VideoSeconds    float64  `json:"videoSeconds"`
	SourceSHA256    string   `json:"sourceSHA256"`
	SourceBytes     int64    `json:"sourceBytes"`
	Timing          []Timing `json:"timing"`
	ElapsedSeconds  float64  `json:"elapsedSeconds"`
	FramesPerSecond float64  `json:"renderedFramesPerSecond"`
	PeakRSSBytes    int64    `json:"observedPeakRSSBytes"`
}

const (
	MaxCastBytes   int64 = 512 << 20
	MaxOutputBytes int64 = 1 << 30
	MaxJobBytes    int64 = 2 << 30
	MaxRSSBytes    int64 = 1536 << 20
	MaxFrames            = 108000
	// MaxJobAge is the default render deadline; a FrameRequest may ask for a
	// longer one (MaxAge) up to MaxJobAgeLimit, so a long frame count is not
	// killed by a fixed deadline.
	MaxJobAge      = 30 * time.Minute
	MaxJobAgeLimit = 6 * time.Hour
)

// crashDumpEnv points Chromium's crash handler (crashpad) at the job's private
// directory. --disable-crash-reporter and --disable-breakpad do not stop
// crashpad creating "Crash Reports" under the user's ~/.config/chromium; the
// BREAKPAD_DUMP_LOCATION override does, and the directory is removed with the
// job's other private staging.
func crashDumpEnv(dir string) chromedp.ExecAllocatorOption {
	return chromedp.Env("BREAKPAD_DUMP_LOCATION=" + filepath.Join(dir, "crash"))
}

var ErrBusy = errors.New("video export capacity exhausted")

// One process-wide permit bounds heavy browser/encoder jobs even across Renderer
// instances. The application may impose a stricter queue/cancellation policy.
var permit = make(chan struct{}, 1)

type Renderer struct{ config Config }

func New(config Config) (*Renderer, error) {
	if !platformSupported() {
		return nil, errors.New("video export currently qualified on Linux only")
	}
	for _, p := range []*string{&config.Chromium, &config.FFmpeg, &config.FFprobe} {
		if *p == "" {
			return nil, errors.New("video export requires explicit Chromium, FFmpeg and FFprobe executables")
		}
		resolved, err := exec.LookPath(*p)
		if err != nil {
			return nil, fmt.Errorf("video prerequisite: %w", err)
		}
		*p = resolved
	}
	if len(config.Assets.PlayerJS) == 0 || len(config.Assets.PlayerCSS) == 0 || len(config.Assets.Font) == 0 || len(config.Assets.PlayerJS) > 8<<20 || len(config.Assets.PlayerCSS) > 1<<20 || len(config.Assets.Font) > 2<<20 || len(config.Assets.BoxFont) > 1<<20 {
		return nil, errors.New("missing or oversized official player assets")
	}
	config.Assets = Assets{append([]byte(nil), config.Assets.PlayerJS...), append([]byte(nil), config.Assets.PlayerCSS...), append([]byte(nil), config.Assets.Font...), append([]byte(nil), config.Assets.BoxFont...)}
	return &Renderer{config}, nil
}

func timing(req Request) (Result, error) {
	r := Result{Codec: req.Codec, FPS: req.FPS, Width: req.Width, Height: req.Height}
	if req.Codec != "h264" && req.Codec != "prores" {
		return r, errors.New("unsupported video codec")
	}
	if req.FPS < 1 || req.FPS > 60 || req.Width < 160 || req.Width > 1920 || req.Height < 120 || req.Height > 1080 || req.Width%2 != 0 || req.Height%2 != 0 {
		return r, errors.New("unsupported video geometry or frame rate")
	}
	if len(req.Spans) == 0 || len(req.Spans) > 1024 {
		return r, errors.New("video needs 1..1024 timing spans")
	}
	for i, s := range req.Spans {
		if math.IsNaN(s.Start) || math.IsNaN(s.End) || math.IsInf(s.Start, 0) || math.IsInf(s.End, 0) || s.Start < 0 || s.End <= s.Start || s.End > 315360000 || s.Segment < 0 || (i > 0 && s.Start < req.Spans[i-1].End) {
			return r, errors.New("invalid or overlapping source timing")
		}
		count := math.Ceil((s.End - s.Start) * float64(req.FPS))
		if count > MaxFrames || r.Frames+int(count) > MaxFrames {
			return r, errors.New("video frame limit exceeded")
		}
		frames := int(count)
		// Floating subtraction/multiplication may put an exact frame boundary
		// just above an integer; never sample outside the half-open span.
		for frames > 1 && s.Start+float64(frames-1)/float64(req.FPS) >= s.End {
			frames--
		}
		if s.WallStart != nil {
			copied := *s.WallStart
			s.WallStart = &copied
		}
		if s.WallEnd != nil {
			copied := *s.WallEnd
			s.WallEnd = &copied
		}
		r.Timing = append(r.Timing, Timing{Span: s, FirstFrame: r.Frames, Frames: frames})
		r.Frames += frames
	}
	r.VideoSeconds = float64(r.Frames) / float64(req.FPS)
	return r, nil
}

// Render copies the fixed input privately, renders deterministic timestamps and
// verifies the encoded stream before atomically linking a finished artifact into
// Output. Every failure/cancellation removes owned staging; no output is replaced.
func (r *Renderer) Render(parent context.Context, req Request) (result Result, err error) {
	result, err = timing(req)
	if err != nil {
		return Result{}, err
	}
	if req.Cast == nil || !filepath.IsAbs(req.Output) || filepath.Clean(req.Output) != req.Output {
		return Result{}, errors.New("explicit immutable cast and absolute clean output path required")
	}
	if _, err := os.Lstat(req.Output); !errors.Is(err, os.ErrNotExist) {
		return Result{}, errors.New("output already exists or is inaccessible")
	}
	select {
	case permit <- struct{}{}:
		defer func() { <-permit }()
	default:
		return Result{}, ErrBusy
	}
	ctx, cancel := context.WithTimeout(parent, MaxJobAge)
	defer cancel()
	start := time.Now()
	dir, err := os.MkdirTemp(filepath.Dir(req.Output), ".areel-video-")
	if err != nil {
		return Result{}, err
	}
	defer os.RemoveAll(dir)
	castPath := filepath.Join(dir, "source.cast")
	f, err := os.OpenFile(castPath, os.O_WRONLY|os.O_CREATE|os.O_EXCL, 0600)
	if err != nil {
		return Result{}, err
	}
	hash := sha256.New()
	n, copyErr := io.Copy(io.MultiWriter(f, hash), io.LimitReader(contextReader{ctx, req.Cast}, MaxCastBytes+1))
	closeErr := f.Close()
	if copyErr != nil || closeErr != nil {
		return Result{}, errors.Join(copyErr, closeErr)
	}
	if n == 0 || n > MaxCastBytes {
		return Result{}, errors.New("video cast input exceeds policy or is empty")
	}
	if err = admitCast(ctx, castPath); err != nil {
		return Result{}, err
	}
	result.SourceBytes = n
	result.SourceSHA256 = hex.EncodeToString(hash.Sum(nil))
	listener, err := net.Listen("tcp4", "127.0.0.1:0")
	if err != nil {
		return Result{}, err
	}
	origin := "http://" + listener.Addr().String()
	server := &http.Server{Handler: r.handler(castPath, listener.Addr().String()), ReadHeaderTimeout: 3 * time.Second, WriteTimeout: 30 * time.Second, IdleTimeout: 5 * time.Second, MaxHeaderBytes: 8192}
	served := make(chan struct{})
	go func() { defer close(served); _ = server.Serve(listener) }()
	defer func() { _ = server.Close(); <-served }()
	profile := filepath.Join(dir, "profile")
	options := append(chromedp.DefaultExecAllocatorOptions[:], chromedp.ExecPath(r.config.Chromium), chromedp.UserDataDir(profile), chromedp.WindowSize(req.Width, req.Height), chromedp.Flag("host-resolver-rules", "MAP * ~NOTFOUND, EXCLUDE 127.0.0.1"), chromedp.Flag("proxy-server", origin), chromedp.Flag("proxy-bypass-list", "127.0.0.1"), chromedp.Flag("js-flags", "--max-old-space-size=512"), chromedp.Flag("disable-crash-reporter", true), chromedp.Flag("disable-breakpad", true), crashDumpEnv(dir), chromedp.ModifyCmdFunc(ownCommand))
	if r.config.NoSandbox {
		options = append(options, chromedp.NoSandbox)
	}
	allocated, stopAllocator := chromedp.NewExecAllocator(ctx, options...)
	defer stopAllocator()
	browser, stopBrowser := chromedp.NewContext(allocated)
	defer stopBrowser()
	if err = chromedp.Run(browser); err != nil {
		return Result{}, err
	}
	monitorCtx, stopMonitor := context.WithCancel(browser)
	monitored := make(chan struct{})
	var monitorErr error
	var peak int64
	var encoderPID atomic.Int64
	go func() {
		defer close(monitored)
		monitorErr = watchResources(monitorCtx, browser, dir, &encoderPID, &peak)
		if monitorErr != nil {
			cancel()
		}
	}()
	defer func() {
		stopMonitor()
		<-monitored
		if monitorErr != nil {
			result, err = Result{}, monitorErr
		}
	}()
	if err = chromedp.Run(browser, emulation.SetDeviceMetricsOverride(int64(req.Width), int64(req.Height), 1, false), chromedp.Navigate(origin+"/"), chromedp.Poll(`window.exportReady === true || window.exportError !== undefined`, nil)); err != nil {
		return Result{}, fmt.Errorf("video renderer initialization: %w", err)
	}
	var readyError string
	if err = chromedp.Run(browser, chromedp.Evaluate(`window.exportError || ''`, &readyError)); err != nil {
		return Result{}, err
	}
	if readyError != "" {
		return Result{}, errors.New("official player could not load supplied cast")
	}
	var duration float64
	if err = chromedp.Run(browser, chromedp.Evaluate(`player.getDuration()`, &duration)); err != nil {
		return Result{}, err
	}
	if result.Timing[len(result.Timing)-1].End > duration+0.000001 {
		return Result{}, errors.New("requested video extends beyond supplied cast")
	}
	staged := filepath.Join(dir, "video")
	args := encoderArgs(strconv.Itoa(req.FPS), result.Frames, req.Codec, "", staged)
	encoder := exec.CommandContext(ctx, r.config.FFmpeg, args...)
	ownCommand(encoder)
	input, err := encoder.StdinPipe()
	if err != nil {
		return Result{}, err
	}
	stderr := &boundedLog{}
	encoder.Stderr = stderr
	if err = encoder.Start(); err != nil {
		return Result{}, err
	}
	waited := false
	defer func() {
		_ = input.Close()
		if !waited {
			cancel()
			_ = encoder.Wait()
		}
	}()
	encoderPID.Store(int64(encoder.Process.Pid))
	for _, span := range result.Timing {
		for i := 0; i < span.Frames; i++ {
			at := span.Start + float64(i)/float64(req.FPS)
			var png []byte
			err = chromedp.Run(browser, chromedp.Evaluate(fmt.Sprintf(`paintAt(%s)`, strconv.FormatFloat(at, 'f', -1, 64)), nil, func(p *runtime.EvaluateParams) *runtime.EvaluateParams { return p.WithAwaitPromise(true) }), chromedp.ActionFunc(func(ctx context.Context) error {
				var e error
				png, e = page.CaptureScreenshot().WithFormat(page.CaptureScreenshotFormatPng).WithClip(&page.Viewport{X: 0, Y: 0, Width: float64(req.Width), Height: float64(req.Height), Scale: 1}).Do(ctx)
				return e
			}))
			if err != nil {
				return Result{}, fmt.Errorf("video painted frame %d: %w", span.FirstFrame+i, err)
			}
			if len(png) > 16<<20 {
				return Result{}, errors.New("video screenshot exceeds frame bound")
			}
			if _, err = input.Write(png); err != nil {
				return Result{}, fmt.Errorf("video encoder pipe: %w", err)
			}
		}
	}
	_ = input.Close()
	err = encoder.Wait()
	waited = true
	stopMonitor()
	<-monitored
	result.PeakRSSBytes = peak
	if monitorErr != nil {
		return Result{}, monitorErr
	}
	if err != nil {
		return Result{}, fmt.Errorf("video encoder: %w (%s)", err, stderr.String())
	}
	info, err := os.Stat(staged)
	if err != nil {
		return Result{}, err
	}
	if info.Size() == 0 || info.Size() >= MaxOutputBytes {
		return Result{}, errors.New("video output limit reached")
	}
	if err = r.verify(ctx, staged, result); err != nil {
		return Result{}, err
	}
	if err = ctx.Err(); err != nil {
		return Result{}, err
	}
	file, err := os.OpenFile(staged, os.O_RDWR, 0600)
	if err != nil {
		return Result{}, err
	}
	if err = file.Chmod(0600); err == nil {
		err = file.Sync()
	}
	err = errors.Join(err, file.Close())
	if err != nil {
		return Result{}, err
	}
	result.ElapsedSeconds = time.Since(start).Seconds()
	result.FramesPerSecond = float64(result.Frames) / result.ElapsedSeconds
	if err = os.Link(staged, req.Output); err != nil {
		return Result{}, fmt.Errorf("publish video: %w", err)
	}
	return result, nil
}

// encoderArgs is the FFmpeg argv shared by Render and RenderFrames. framerate is
// FFmpeg's input rate ("30" or "30000/1001"). A non-empty chapters path adds a
// private ffmetadata input whose chapters are muxed in the same encode; without
// it the argv is exactly the legacy Render argv.
func encoderArgs(framerate string, frames int, codec, chapters, staged string) []string {
	args := []string{"-hide_banner", "-loglevel", "error", "-nostdin", "-y", "-threads", "2", "-filter_threads", "1", "-f", "image2pipe", "-framerate", framerate, "-c:v", "png", "-i", "pipe:0"}
	if chapters != "" {
		args = append(args, "-f", "ffmetadata", "-i", chapters, "-map", "0:v:0", "-map_chapters", "1")
	}
	args = append(args, "-an", "-frames:v", strconv.Itoa(frames))
	if codec == "h264" {
		args = append(args, "-c:v", "libx264", "-preset", "veryfast", "-pix_fmt", "yuv420p", "-movflags", "+faststart", "-f", "mp4")
	} else {
		args = append(args, "-c:v", "prores_ks", "-profile:v", "3", "-pix_fmt", "yuv422p10le", "-f", "mov")
	}
	return append(args, "-threads", "2", "-fs", strconv.FormatInt(MaxOutputBytes, 10), staged)
}

type contextReader struct {
	ctx context.Context
	r   io.Reader
}

func (r contextReader) Read(b []byte) (int, error) {
	if err := r.ctx.Err(); err != nil {
		return 0, err
	}
	return r.r.Read(b)
}

type boundedLog struct {
	mu   sync.Mutex
	data []byte
}

func (b *boundedLog) Write(p []byte) (int, error) {
	b.mu.Lock()
	defer b.mu.Unlock()
	n := len(p)
	if len(b.data) < 4096 {
		b.data = append(b.data, p[:min(len(p), 4096-len(b.data))]...)
	}
	return n, nil
}
func (b *boundedLog) String() string { b.mu.Lock(); defer b.mu.Unlock(); return string(b.data) }

func (r *Renderer) verify(ctx context.Context, path string, want Result) error {
	cmd := exec.CommandContext(ctx, r.config.FFprobe, "-v", "error", "-count_frames", "-select_streams", "v:0", "-show_entries", "stream=codec_name,width,height,nb_read_frames,duration", "-of", "json", path)
	ownCommand(cmd)
	output := &boundedLog{}
	cmd.Stdout = output
	cmd.Stderr = io.Discard
	if err := cmd.Run(); err != nil {
		return fmt.Errorf("video verification: %w", err)
	}
	var probe struct {
		Streams []struct {
			Codec         string `json:"codec_name"`
			Width, Height int
			Frames        string `json:"nb_read_frames"`
			Duration      string `json:"duration"`
		}
	}
	if err := json.Unmarshal([]byte(output.String()), &probe); err != nil {
		return err
	}
	if len(probe.Streams) != 1 {
		return errors.New("video missing verified stream")
	}
	got := probe.Streams[0]
	frames, _ := strconv.Atoi(got.Frames)
	seconds, _ := strconv.ParseFloat(got.Duration, 64)
	if got.Codec != want.Codec || frames != want.Frames || got.Width != want.Width || got.Height != want.Height || math.Abs(seconds-want.VideoSeconds) > 1/float64(want.FPS)+0.001 {
		return errors.New("video frame count, duration or codec mismatch")
	}
	return nil
}

func (r *Renderer) handler(castPath, host string) http.Handler {
	return http.HandlerFunc(func(w http.ResponseWriter, q *http.Request) {
		peer, _, _ := net.SplitHostPort(q.RemoteAddr)
		if q.Host != host || !net.ParseIP(peer).IsLoopback() || q.Method != "GET" || q.URL.RawQuery != "" || q.ContentLength != 0 {
			http.Error(w, "refused", 403)
			return
		}
		w.Header().Set("Cache-Control", "no-store")
		w.Header().Set("Content-Security-Policy", "default-src 'none'; script-src 'self' 'unsafe-inline' 'wasm-unsafe-eval'; style-src 'self' 'unsafe-inline'; font-src 'self'; connect-src 'self'")
		switch q.URL.Path {
		case "/":
			w.Header().Set("Content-Type", "text/html; charset=utf-8")
			io.WriteString(w, rendererHTML)
		case "/player.js":
			w.Header().Set("Content-Type", "text/javascript")
			w.Write(r.config.Assets.PlayerJS)
		case "/player.css":
			w.Header().Set("Content-Type", "text/css")
			w.Write(r.config.Assets.PlayerCSS)
		case "/DejaVuSansMono.ttf":
			w.Header().Set("Content-Type", "font/ttf")
			w.Write(r.config.Assets.Font)
		case "/AgentReelBox.ttf":
			if len(r.config.Assets.BoxFont) == 0 {
				http.NotFound(w, q)
				return
			}
			w.Header().Set("Content-Type", "font/ttf")
			w.Write(r.config.Assets.BoxFont)
		case "/source.cast":
			w.Header().Set("Content-Type", "application/x-asciicast")
			f, err := os.Open(castPath)
			if err != nil {
				http.Error(w, "unavailable", 500)
				return
			}
			defer f.Close()
			io.Copy(w, f)
		default:
			http.NotFound(w, q)
		}
	})
}

