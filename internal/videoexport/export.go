func watchResources(ctx, browser context.Context, dir string, encoderPID *atomic.Int64, peak *int64) error {
	tick := time.NewTicker(200 * time.Millisecond)
	defer tick.Stop()
	for {
		select {
		case <-ctx.Done():
			return nil
		case <-tick.C:
			size, err := jobSize(dir)
			if err != nil {
				return err
			}
			if size > MaxJobBytes {
				return errors.New("video temporary disk budget exceeded")
			}
			processes, err := systeminfo.GetProcessInfo().Do(cdp.WithExecutor(ctx, chromedp.FromContext(browser).Browser))
			if err != nil {
				if ctx.Err() != nil {
					return nil
				}
				return fmt.Errorf("video memory observation: %w", err)
			}
			if len(processes) > 64 {
				return errors.New("video process limit exceeded")
			}
			var pids []int
			if pid := encoderPID.Load(); pid > 0 {
				pids = append(pids, int(pid))
			}
			for _, p := range processes {
				pids = append(pids, int(p.ID))
			}
			var total int64
			for _, pid := range pids {
				rss, err := processRSS(pid)
				if errors.Is(err, os.ErrNotExist) {
					continue
				}
				if err != nil {
					return err
				}
				total += rss
			}
			if total > *peak {
				*peak = total
			}
			if total > MaxRSSBytes {
				return errors.New("video process memory budget exceeded")
			}
		}
	}
}
func jobSize(dir string) (int64, error) {
	var bytes int64
	entries := 0
	err := filepath.WalkDir(dir, func(path string, d os.DirEntry, err error) error {
		if errors.Is(err, os.ErrNotExist) {
			return nil
		}
		if err != nil {
			return err
		}
		entries++
		if entries > 20000 {
			return errors.New("video temporary file count limit")
		}
		if d.Type().IsRegular() {
			s, e := d.Info()
			if errors.Is(e, os.ErrNotExist) {
				return nil
			}
			if e != nil {
				return e
			}
			bytes += s.Size()
		}
		return nil
	})
	return bytes, err
}
